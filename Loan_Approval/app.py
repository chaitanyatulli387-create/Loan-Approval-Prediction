import streamlit as st
import pandas as pd
import joblib

st.set_page_config(
    page_title="Loan Approval Prediction",
    page_icon="🏦",
    layout="wide"
)

model = joblib.load("models/loan_approval_model.pkl")

st.title("🏦 Loan Approval Prediction")
st.write("Enter the applicant details to check loan eligibility.")

st.divider()

st.subheader("👤 Applicant Details")

col1, col2, col3 = st.columns(3)

with col1:
    gender = st.selectbox(
        "Gender",
        ["Male", "Female"]
    )

with col2:
    married = st.selectbox(
        "Married",
        ["Yes", "No"]
    )

with col3:
    dependents = st.selectbox(
        "Dependents",
        ["0", "1", "2", "3+"]
    )

col1, col2 = st.columns(2)

with col1:
    education = st.selectbox(
        "Education",
        ["Graduate", "Not Graduate"]
    )

with col2:
    self_employed = st.selectbox(
        "Self Employed",
        ["Yes", "No"]
    )

st.subheader("💰 Financial Details")

col1, col2 = st.columns(2)

with col1:
    applicant_income = st.number_input(
        "Applicant Income",
        min_value=0.0,
        value=5000.0,
        step=500.0
    )

with col2:
    coapplicant_income = st.number_input(
        "Coapplicant Income",
        min_value=0.0,
        value=2000.0,
        step=500.0
    )

col1, col2 = st.columns(2)

with col1:
    loan_amount = st.number_input(
        "Loan Amount",
        min_value=1.0,
        value=150.0,
        step=10.0
    )

with col2:
    loan_term = st.selectbox(
        "Loan Amount Term",
        [120.0, 180.0, 240.0, 300.0, 360.0, 480.0],
        index=4
    )

st.subheader("🏠 Credit & Property Details")

col1, col2 = st.columns(2)

with col1:
    credit_history = st.selectbox(
        "Credit History",
        ["Good", "Poor"]
    )

    if credit_history == "Good":
        credit_value = 1.0
    else:
        credit_value = 0.0

with col2:
    property_area = st.selectbox(
        "Property Area",
        ["Urban", "Semiurban", "Rural"]
    )

st.divider()

check_loan = st.button(
    "🔍 CHECK LOAN ELIGIBILITY",
    use_container_width=True
)

if check_loan:

    input_data = pd.DataFrame({
        "Gender": [gender],
        "Married": [married],
        "Dependents": [dependents],
        "Education": [education],
        "Self_Employed": [self_employed],
        "ApplicantIncome": [applicant_income],
        "CoapplicantIncome": [coapplicant_income],
        "LoanAmount": [loan_amount],
        "Loan_Amount_Term": [loan_term],
        "Credit_History": [credit_value],
        "Property_Area": [property_area]
    })

    prediction = model.predict(input_data)[0]

    probability = model.predict_proba(input_data)[0][1] * 100

    st.divider()

    st.subheader("📋 Loan Eligibility Result")

    if prediction == 1:
        st.success("🟢 LOAN APPROVED")
    else:
        st.error("🔴 LOAN NOT APPROVED")

    st.metric(
        "Approval Probability",
        f"{probability:.2f}%"
    )

    st.caption(
        "This prediction is generated by a machine learning model "
        "for educational purposes."
    )